def main():
    with open('data/vocab.json', encoding='utf-8') as f:
        d = json.load(f)
    cards = [(k, v['cmp']) for k, v in d.items() if isinstance(v, dict) and isinstance(v.get('cmp'), dict)]

    dims = Counter()
    for k, cmp in cards:
        for row in cmp.get('diff') or []:
            if row.get('dim'):
                dims[row['dim']] += 1

    changed, suspect = [], []
    for v, n in dims.most_common():
        nv = dim_norm(v)
        if nv != v:
            changed.append((n, v, nv))
        if SUSPECT.search(nv):
            suspect.append((n, v, nv))

    print(f'dim 种数 {len(dims)}；改动 {len(changed)} 种；仍可疑 {len(suspect)} 种')
    with open('work/dim_final.txt', 'w', encoding='utf-8') as f:
        for n, v, nv in suspect:
            f.write(f'{n}\t{v}\t=\t{nv}\n')
    print('可疑清单 → work/dim_final.txt')
    for n, v, nv in suspect:
        print(f'  {n}\t{v}\t=\t{nv}')


if __name__ == '__main__':
    main()
