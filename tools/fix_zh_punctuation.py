PUNCT = '，。、；：！？“”（）'
SECTIONS = 'shadow/data/sections.json'


def main():
    apply = '--apply' in sys.argv
    D = json.load(open(SECTIONS, encoding='utf-8'))
    flat = [(ci, si, k) for ci, c in enumerate(D) for si, pp in enumerate(c['sentZh']) for k in range(len(pp))]
    assert len(flat) == 1810, len(flat)
    done = 0
    for gi, new in FIX.items():
        ci, si, k = flat[gi]
        old = D[ci]['sentZh'][si][k]
        bare = re.sub('[' + PUNCT + ']', '', new)
        if bare != old:
            print(f'#{gi} 拒绝：去标点后与原文不一致\n  旧 {old}\n  新 {bare}')
            return 1
        if re.search('[' + PUNCT + ']', old):
            print(f'#{gi} 前提不成立：原文其实已有标点')
            return 1
        if apply:
            D[ci]['sentZh'][si][k] = new
        done += 1
    print(('已补标点 ' if apply else '校验通过（干跑）') + f'{done} 条')
    if apply:
        total = sum(len(p) for c in D for p in c['paragraphs'])
        assert total == 1810
        json.dump(D, open(SECTIONS, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
