def dim_norm(orig):
    if not orig:
        return orig
    if orig in EXACT_FULL:
        return EXACT_FULL[orig]
    o = orig
    for pat, rep in PRE:
        o = re.sub(pat, rep, o)
    for pat, rep in TERM:
        o = re.sub(pat, rep, o)
    for pat, rep in POST:
        o = re.sub(pat, rep, o)
    return o


